"""Run the challenge test set through both stages and record what actually happened.

Run from the project folder:   .venv/bin/python tests/run_challenge.py [case_id ...]
Needs GROQ_API_KEY in .env for the fact-check stage (cases are recorded as "unavailable" otherwise).
Writes tests/challenge_results.json and tests/challenge_results.md. Uses live web search, so results can
vary between runs; each run is timestamped.
"""
import datetime, json, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import app, factcheck

CATS = ["likely_real", "likely_fake", "unverified"]


def run_case(c):
    pred = app.analyse(c["title"], c["text"])
    t0, fc, tries = time.time(), None, 0
    while tries < 5:
        tries += 1
        fc = factcheck.check(c["title"], c["text"], pred)
        if fc.get("code") == "retry" and "rate limit" in fc.get("error", ""):
            print(f"   rate limited, waiting 65 s (attempt {tries})", flush=True)
            time.sleep(65)
            continue
        break
    claims = fc.get("claims", [])
    srcs = [s for cl in claims for s in cl["sources"]]
    category = fc.get("category", "unverified")    # an unavailable check is shown to the user as unverified
    return {
        "id": c["id"], "type": c["type"], "fictional": c["fictional"], "expected": c["expected"], "acceptable": c["acceptable"],
        "style_model": {"label": pred["label"], "margin": pred["score"]},
        "factcheck_available": "error" not in fc, "factcheck_error": fc.get("error"),
        "category": category, "rule": fc.get("rule"), "evidence_strength": fc.get("evidence_strength", "none"),
        "article_type": fc.get("article_type"),
        "headline_misleading": (fc.get("headline_check") or {}).get("misleading"),
        "old_news_as_new": (fc.get("timeliness") or {}).get("old_news_presented_as_new"),
        "claims": [{"claim": cl["claim"], "central": cl["central"], "status": cl["status"],
                    "sources": [f"{s['domain']} ({s['tier']}{', excerpt verified' if s['excerpt_verified'] else ''})" for s in cl["sources"]]}
                   for cl in claims],
        "sources_cited": len(srcs), "primary_sources": sum(s["tier"] == "primary" for s in srcs),
        "excerpts_verified": sum(s["excerpt_verified"] for s in srcs), "pages_retrieved": fc.get("pages_retrieved", 0),
        "seconds": round(time.time() - t0, 1),
        "exact": category == c["expected"], "acceptable_result": category in c["acceptable"],
        "critical_error": (category == "likely_real" and c["expected"] != "likely_real") or
                          (category == "likely_fake" and c["expected"] == "likely_real"),
    }


def summarise(rows):
    avail = [r for r in rows if r["factcheck_available"]]
    conf = {e: {a: 0 for a in CATS} for e in CATS}
    for r in rows:
        conf[r["expected"]][r["category"]] += 1
    binary = [r for r in rows if r["expected"] in ("likely_real", "likely_fake")]
    svm_ok = sum((r["style_model"]["label"] == "fake") == (r["expected"] == "likely_fake") for r in binary)
    return {
        "cases": len(rows), "factcheck_available": len(avail),
        "exact_match": sum(r["exact"] for r in rows), "acceptable": sum(r["acceptable_result"] for r in rows),
        "critical_errors": sum(r["critical_error"] for r in rows),
        "fabricated_or_misleading_labelled_real": sum(r["category"] == "likely_real" and r["expected"] != "likely_real" for r in rows),
        "style_model_binary_accuracy": f"{svm_ok}/{len(binary)}",
        "style_model_fabricated_called_real": sum(r["style_model"]["label"] == "real" and r["fictional"] and r["expected"] == "likely_fake" for r in rows),
        "confusion_expected_vs_actual": conf,
    }


def write_md(res):
    S, rows = res["summary"], res["results"]
    L = [f"# Challenge test results — {res['run_at']}", "",
         "Generated by `tests/run_challenge.py` with live web search (results can vary between runs).",
         f"Fact-check model: {res['model']}. Fictional articles are test material only.", "",
         "## Summary", "",
         f"- Cases: {S['cases']} (fact-check available for {S['factcheck_available']})",
         f"- Exact category match: **{S['exact_match']}/{S['cases']}** · acceptable category: **{S['acceptable']}/{S['cases']}**",
         f"- Critical errors (fabricated/misleading shown as *Likely real*, or genuine shown as *Likely fake*): **{S['critical_errors']}**",
         f"- Writing-style model alone, on cases whose expected label is real or fake: **{S['style_model_binary_accuracy']}** correct; "
         f"it called **{S['style_model_fabricated_called_real']}** fabricated/misleading articles real.", "",
         "Confusion (rows = expected, columns = actual):", "",
         "| expected \\ actual | likely_real | likely_fake | unverified |", "|---|---|---|---|",
         *[f"| {e} | " + " | ".join(str(S["confusion_expected_vs_actual"][e][a]) for a in CATS) + " |" for e in CATS], "",
         "## Per case", "",
         "| Case | Type | Expected | Actual | OK? | Style model | Evidence | Sources (primary / verified excerpts) | Rule |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ok = "✅ exact" if r["exact"] else ("☑️ acceptable" if r["acceptable_result"] else "❌")
        sm = f"{r['style_model']['label']} ({r['style_model']['margin']:+.2f})"
        rule = r["rule"] or f"unavailable: {r['factcheck_error']}"
        L.append(f"| `{r['id']}` | {r['type']} | {r['expected']} | **{r['category']}** | {ok} | {sm} | {r['evidence_strength']} | "
                 f"{r['sources_cited']} ({r['primary_sources']} / {r['excerpts_verified']}) | {rule} |")
    L += ["", "## Claims checked per case", ""]
    for r in rows:
        L.append(f"**{r['id']}** → {r['category']}")
        for cl in r["claims"]:
            L.append(f"- [{cl['status']}{', central' if cl['central'] else ''}] {cl['claim']} — " + (", ".join(cl["sources"]) or "no retrieved source"))
        L.append("")
    (ROOT / "tests" / "challenge_results.md").write_text("\n".join(L))


def main():
    cases = json.loads((ROOT / "tests" / "challenge_set.json").read_text())["cases"]
    only = set(sys.argv[1:])
    rows = []
    for i, c in enumerate([c for c in cases if not only or c["id"] in only]):
        if i:
            time.sleep(20)                             # stay under Groq's per-minute token limit
        print(f"[{i + 1}] {c['id']} ...", flush=True)
        r = run_case(c)
        rows.append(r)
        print(f"    expected {r['expected']:<12} actual {r['category']:<12} {'OK' if r['acceptable_result'] else 'WRONG'}"
              f" | style {r['style_model']['label']} | evidence {r['evidence_strength']} | {r['seconds']}s", flush=True)
    res = {"run_at": datetime.datetime.now().isoformat(timespec="seconds"),
           "model": factcheck.load_env().get("GROQ_MODEL") or factcheck.DEFAULT_MODEL,
           "summary": summarise(rows), "results": rows}
    (ROOT / "tests" / "challenge_results.json").write_text(json.dumps(res, indent=2))
    write_md(res)
    print(json.dumps(res["summary"], indent=1))


if __name__ == "__main__":
    main()
